#!/bin/bash
# =============================================================
# deploy-photos-ui.sh — Build Angular photos UI & deploy to EC2
# Usage: bash scripts/deploy-photos-ui.sh
# =============================================================

set -euo pipefail
source "$(dirname "$0")/config.sh"

REMOTE_WEB_DIR="$APP_DIR/photos-ui"
NGINX_CONF_NAME="photos-ui.conf"
WEB_PORT=4201

BOLD='\033[1m'; GREEN='\033[0;32m'; RED='\033[0;31m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; RESET='\033[0m'

log()    { echo -e "${CYAN}>>> $*${RESET}"; }
ok()     { echo -e "${GREEN}  ✓ $*${RESET}"; }
header() { echo -e "\n${BOLD}$*${RESET}"; }

# ══════════════════════════════════════════════════════════════
# 1. Build Angular (production)
# ══════════════════════════════════════════════════════════════
header "════════════════════════════════════════"
header " Building Photos UI (production)"
header "════════════════════════════════════════"

if [ ! -d "$PHOTOS_UI_DIR" ]; then
  echo -e "${RED}ERROR: photos-ui directory not found at $PHOTOS_UI_DIR${RESET}"
  exit 1
fi

cd "$PHOTOS_UI_DIR"

if [ ! -d "node_modules" ]; then
  log "Installing npm dependencies..."
  npm install --silent
fi

log "Running: ng build --configuration production"
npm run build -- --configuration production
ok "Build complete"

DIST_DIR="$PHOTOS_UI_DIR/dist/photos-ui/browser"
if [ ! -d "$DIST_DIR" ]; then
  echo -e "${RED}ERROR: dist not found at $DIST_DIR${RESET}"
  exit 1
fi

log "Dist size: $(du -sh "$DIST_DIR" | cut -f1)"

# ══════════════════════════════════════════════════════════════
# 2. Upload dist to EC2
# ══════════════════════════════════════════════════════════════
header "════════════════════════════════════════"
header " Uploading to EC2"
header "════════════════════════════════════════"

$SSH_CMD "mkdir -p $REMOTE_WEB_DIR"

log "Packaging and uploading..."
TARBALL="/tmp/photos-ui-$(date +%s).tar.gz"
tar czf "$TARBALL" -C "$DIST_DIR" .
scp -i "$EC2_KEY" -o StrictHostKeyChecking=no "$TARBALL" "$EC2_USER@$EC2_HOST:/tmp/photos-ui.tar.gz"
rm -f "$TARBALL"

$SSH_CMD "tar xzf /tmp/photos-ui.tar.gz -C $REMOTE_WEB_DIR && rm /tmp/photos-ui.tar.gz"
$SSH_CMD "chmod o+x /home/ec2-user /home/ec2-user/sevis && chmod -R o+rX $REMOTE_WEB_DIR"
ok "Upload complete"

# ══════════════════════════════════════════════════════════════
# 3. Write nginx server block and activate
# ══════════════════════════════════════════════════════════════
header "════════════════════════════════════════"
header " Configuring nginx (port $WEB_PORT)"
header "════════════════════════════════════════"

NGINX_CONF_LOCAL="/tmp/$NGINX_CONF_NAME"
cat > "$NGINX_CONF_LOCAL" << EOF
# Photos UI — Angular SPA
# Generated by deploy-photos-ui.sh on $(date)

server {
    listen ${WEB_PORT};
    server_name _;

    root ${REMOTE_WEB_DIR};
    index index.html;

    # Mirrors proxy.conf.json (Angular local dev) so /user-service and
    # /photo-service work the same way in prod as they do in dev — without
    # these, requests to those paths fall through to try_files below and
    # return the SPA's index.html instead of hitting the gateway on :8080.
    location /user-service/ {
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
    }

    location /photo-service/ {
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
    }

    location /stream-service/ {
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
    }

    location / {
        try_files \$uri \$uri/ /index.html;
    }

    location = /index.html {
        add_header Cache-Control "no-store, no-cache, must-revalidate";
        add_header Pragma "no-cache";
    }

    location ~* \.(js|css)$ {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }

    location ~* \.(png|jpg|jpeg|gif|ico|svg|woff2?|ttf|eot)$ {
        expires 30d;
        add_header Cache-Control "public";
    }

    gzip on;
    gzip_vary on;
    gzip_proxied any;
    gzip_comp_level 6;
    gzip_types text/plain text/css text/javascript application/javascript application/json image/svg+xml;
    gzip_min_length 1024;
}
EOF

scp -i "$EC2_KEY" -o StrictHostKeyChecking=no "$NGINX_CONF_LOCAL" "$EC2_USER@$EC2_HOST:/tmp/$NGINX_CONF_NAME"
rm -f "$NGINX_CONF_LOCAL"

$SSH_CMD bash << NGINXSH
set -e
sudo mv /tmp/$NGINX_CONF_NAME /etc/nginx/conf.d/$NGINX_CONF_NAME
sudo nginx -t 2>&1
sudo systemctl reload nginx
echo "  nginx reloaded"
NGINXSH
ok "nginx configured on port $WEB_PORT"

# ══════════════════════════════════════════════════════════════
# 4. Summary
# ══════════════════════════════════════════════════════════════
echo ""
echo -e "${BOLD}${GREEN}════════════════════════════════════════${RESET}"
echo -e "${BOLD}${GREEN} Photos UI deployed!${RESET}"
echo -e "${BOLD}${GREEN}════════════════════════════════════════${RESET}"
echo ""
echo -e "  Photos UI  : ${CYAN}http://$EC2_HOST:$WEB_PORT${RESET}"
echo -e "  API        : ${CYAN}http://$EC2_HOST:8080/photo-service${RESET}"
echo ""
echo -e "${YELLOW}  NOTE: Ensure port $WEB_PORT is open in your EC2 security group.${RESET}"
echo ""
